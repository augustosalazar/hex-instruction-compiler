export default class alu {

    static add(a: number, b: number): number {
        return a + b;
    }

    static sub(a: number, b: number): number {
        return a - b;
    }

    static and(a: number, b: number): number {
        return a & b;
    }

    static or(a: number, b: number): number {
        return a | b;
    }
}